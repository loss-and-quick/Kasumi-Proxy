//! Generate the frontend's runtime defaults (`frontend/src/generated/defaults.ts`)
//! from Rust — the per-protocol blank profile, the backend constants, and the
//! editor dropdown option lists. Single source: every value here lives once in
//! `kasumi-core` (serde defaults, `pub const`s, enum variants) and is emitted, so
//! the frontend never re-types a default. Emitted by `export_generated`,
//! exactly like `bindings.ts` / `schemas.ts`.

use kasumi_core::core::{default_core_for, tun_by_core_options};
use kasumi_core::enums::{TunEngine, editor_option_lists, tun_knobs};
use kasumi_core::profile::{Protocol, empty_profile};
use kasumi_core::state;
use strum::IntoEnumIterator;

/// The committed defaults file the frontend imports.
pub const DEFAULTS_PATH: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../frontend/src/generated/defaults.ts"
);

const HEADER: &str = "\
// This file is generated by `cargo run -p kasumi-desktop --example codegen`. Do not edit it manually.

import type {
\tAdvancedSettings_Serialize,
\tCongestionControl,
\tCoreEngine,
\tFingerprint,
\tFlow,
\tHeaderType,
\tHysteria2Obfs,
\tLogTarget,
\tPacketEncoding,
\tProfile,
\tProtocol,
\tRoutingMode_Serialize,
\tSecurity,
\tSingboxFragment,
\tSsMethod,
\tSubscription_Serialize,
\tTransport,
\tTunEngine,
\tVmessEnc,
} from \"./bindings\";

";

/// The TS element type for each generated option-list const.
fn opts_type(name: &str) -> &'static str {
    match name {
        "PROTOCOL_OPTS" => "Protocol",
        // The serialize side only: the deserialize union also carries the legacy
        // `bypass-lan` alias, which is read but never written.
        "ROUTING_MODE_OPTS" => "RoutingMode_Serialize",
        "CORE_ENGINE_OPTS" => "CoreEngine",
        "LOG_TARGET_OPTS" => "LogTarget",
        "NETWORK_OPTS" => "Transport[\"kind\"]",
        "SECURITY_OPTS" => "Security",
        "HEADER_TYPE_OPTS" => "HeaderType",
        "VMESS_ENC_OPTS" => "VmessEnc",
        "SS_METHOD_OPTS" => "SsMethod",
        "CONGESTION_OPTS" => "CongestionControl",
        "FINGERPRINT_OPTS" => "Fingerprint",
        "FLOW_OPTS" => "Flow",
        "PACKET_ENCODING_OPTS" => "PacketEncoding",
        "HYSTERIA2_OBFS_OPTS" => "Hysteria2Obfs",
        "SINGBOX_FRAGMENT_OPTS" => "SingboxFragment",
        _ => "string",
    }
}

/// Render the defaults module.
pub fn render() -> String {
    let mut out = String::from(HEADER);

    // Per-protocol blank profile templates (Record<Protocol, Profile>). Built
    // from `empty_profile` so the per-field defaults come from the structs.
    let mut empties = serde_json::Map::new();
    for proto in Protocol::iter() {
        let wire = serde_json::to_value(proto)
            .ok()
            .and_then(|v| v.as_str().map(str::to_owned))
            .unwrap_or_default();
        let profile = serde_json::to_value(empty_profile(proto, "")).expect("serialize empty");
        empties.insert(wire, profile);
    }
    let empties_json =
        serde_json::to_string_pretty(&serde_json::Value::Object(empties)).expect("pretty empties");
    out.push_str(
        "/** Per-protocol blank profile templates; `meta.id`/`meta.groupId` are filled per draft. */\n",
    );
    out.push_str("export const EMPTY_PROFILES = ");
    out.push_str(&empties_json);
    out.push_str(" as unknown as Record<Protocol, Profile>;\n\n");

    // The default advanced settings (serde defaults of `AdvancedSettings`). The
    // frontend's runtime/seed/test settings build on this so a new field is typed
    // once, in Rust — never re-typed on the frontend.
    let settings =
        serde_json::to_value(state::AdvancedSettings::default()).expect("serialize settings");
    let settings_json = serde_json::to_string_pretty(&settings).expect("pretty settings");
    out.push_str(
        "/** Default advanced settings (serde defaults; the single source of settings defaults). */\n",
    );
    out.push_str("export const DEFAULT_ADVANCED_SETTINGS = ");
    out.push_str(&settings_json);
    out.push_str(" as AdvancedSettings_Serialize;\n\n");

    // Backend constants (single source: `kasumi-core` contract/state).
    out.push_str(
        "/* Backend constants (local ports, probe URLs, log rotation, state schema). */\n",
    );
    // Test-core ports are backend-internal now (the daemon leases them from one
    // shared pool); the frontend just names a profile, so they're not exported.
    let nums: [(&str, i64); 6] = [
        (
            "DEFAULT_LOCAL_SOCKS_PORT",
            state::DEFAULT_LOCAL_SOCKS_PORT as i64,
        ),
        (
            "DEFAULT_LOCAL_HTTP_PORT",
            state::DEFAULT_LOCAL_HTTP_PORT as i64,
        ),
        (
            "DEFAULT_LOCAL_PAC_PORT",
            state::DEFAULT_LOCAL_PAC_PORT as i64,
        ),
        ("DEFAULT_LOG_ROTATE_KB", state::DEFAULT_LOG_ROTATE_KB),
        // Stamped on exported backups so a restore runs the right migrations.
        (
            "SCHEMA_VERSION",
            i64::from(kasumi_core::migrate::SCHEMA_VERSION),
        ),
        (
            "WS_HEARTBEAT_MS",
            kasumi_core::contract::WS_HEARTBEAT_MS as i64,
        ),
    ];
    for (name, value) in nums {
        out.push_str(&format!("export const {name} = {value};\n"));
    }
    let strs: [(&str, &str); 5] = [
        ("DEFAULT_DELAY_TEST_URL", state::DEFAULT_DELAY_TEST_URL),
        ("DEFAULT_SPEED_TEST_URL", state::DEFAULT_SPEED_TEST_URL),
        ("DEFAULT_ROUTE_ID", kasumi_core::route::DEFAULT_ROUTE_ID),
        // The Happ release whose request identity happ-sub reproduces.
        ("HAPP_VERSION", kasumi_core::request_identity::HAPP_VERSION),
        // The Incy release whose request happ-sub reproduces.
        ("INCY_VERSION", kasumi_core::request_identity::INCY_VERSION),
    ];
    for (name, value) in strs {
        let json = serde_json::to_string(value).expect("string const");
        out.push_str(&format!("export const {name} = {json};\n"));
    }

    let new_sub = serde_json::json!({
        "autoUpdate": state::NEW_SUB_AUTO_UPDATE,
        "interval": state::NEW_SUB_INTERVAL,
    });
    out.push_str("\n/** What a new subscription starts with until the user changes it. */\n");
    out.push_str(&format!(
        "export const NEW_SUB_DEFAULTS: Pick<Subscription_Serialize, \"autoUpdate\" | \"interval\"> = {new_sub};\n"
    ));

    // Editor dropdown option lists (wire values, declaration order).
    out.push_str("\n/* Editor dropdown option lists (wire values, in declaration order). */\n");
    for (name, values) in editor_option_lists() {
        let arr = serde_json::to_string(&values).expect("option list");
        out.push_str(&format!(
            "export const {name}: {}[] = {arr};\n",
            opts_type(name)
        ));
    }

    let schemes =
        serde_json::to_string(kasumi_core::share::SHARE_LINK_SCHEMES).expect("scheme list");
    out.push_str(
        "\n/** Proxy share-link schemes the backend reads; `http`/`https` count only with userinfo. */\n",
    );
    out.push_str(&format!(
        "export const SHARE_LINK_SCHEMES: string[] = {schemes};\n"
    ));

    // Per-core TUN-engine options (default + valid engines), derived from the
    // backend's own `resolve_tun`/`default_tun_for` so the settings UI never
    // re-encodes the per-core default or the SingboxTun-is-sing-box-only rule.
    let mut by_core = serde_json::Map::new();
    for o in tun_by_core_options() {
        by_core.insert(
            wire(o.core),
            serde_json::json!({ "default": wire(o.default), "valid": o.valid.into_iter().map(wire).collect::<Vec<_>>() }),
        );
    }
    let by_core_json =
        serde_json::to_string_pretty(&serde_json::Value::Object(by_core)).expect("pretty tun map");
    out.push_str(
        "\n/** Per-core TUN engine options (default + selectable), single-sourced from Rust `resolve_tun`. */\n",
    );
    out.push_str("export const TUN_BY_CORE = ");
    out.push_str(&by_core_json);
    out.push_str(" as Record<CoreEngine, { default: TunEngine; valid: TunEngine[] }>;\n");

    // Engine-specific settings per TUN engine (Rust `tun_knobs`), so the settings
    // screen shows each engine's own fields only while that engine is in use.
    let mut knobs = serde_json::Map::new();
    for tun in TunEngine::iter() {
        let specs: Vec<serde_json::Value> = tun_knobs(tun)
            .iter()
            .map(|&k| {
                let mut spec = serde_json::to_value(k.kind()).expect("knob kind");
                spec["field"] = serde_json::Value::String(wire(k));
                spec
            })
            .collect();
        knobs.insert(wire(tun), serde_json::Value::Array(specs));
    }
    let knobs_json =
        serde_json::to_string_pretty(&serde_json::Value::Object(knobs)).expect("pretty tun knobs");
    out.push_str(
        "\n/** Engine-specific settings each TUN engine reads (Rust `tun_knobs`); shared ones (MTU, excludes, strict route) are not listed. */\n",
    );
    out.push_str(
        "export type TunKnobSpec = { field: keyof AdvancedSettings_Serialize } & ({ kind: \"number\" } | { kind: \"choice\"; options: string[] });\n",
    );
    out.push_str("export const TUN_KNOBS_BY_ENGINE = ");
    out.push_str(&knobs_json);
    out.push_str(" as Record<TunEngine, TunKnobSpec[]>;\n");

    // Per-protocol default core (single-sourced from Rust `default_core_for`): the
    // settings screen's per-protocol core table falls back to it, and the dev mock
    // bridge stubs `resolveCores` with it. Full per-profile resolution (capability
    // forces included) goes through the `resolveCores` command instead.
    let mut by_proto = serde_json::Map::new();
    for proto in Protocol::iter() {
        by_proto.insert(
            wire(proto),
            serde_json::Value::String(wire(default_core_for(proto))),
        );
    }
    let by_proto_json = serde_json::to_string_pretty(&serde_json::Value::Object(by_proto))
        .expect("pretty core map");
    out.push_str(
        "\n/** Per-protocol default core (Rust `default_core_for`; full resolution = `resolveCores`). */\n",
    );
    out.push_str("export const DEFAULT_CORE_BY_PROTOCOL = ");
    out.push_str(&by_proto_json);
    out.push_str(" as Record<Protocol, CoreEngine>;\n");

    // Protocols locked to a single core engine (single-sourced from Rust `locked_core_for`).
    let locked_protos: Vec<String> = kasumi_core::core::locked_core_protocols()
        .into_iter()
        .map(wire)
        .collect();
    let locked_json = serde_json::to_string(&locked_protos).expect("locked protos");
    out.push_str(
        "\n/** Protocols only one core implements, single-sourced from Rust capability guards. */\n",
    );
    out.push_str(&format!(
        "export const LOCKED_CORE_PROTOCOLS: readonly Protocol[] = {locked_json} as readonly Protocol[];\n"
    ));

    let mut locked_by_proto = serde_json::Map::new();
    for proto in Protocol::iter() {
        if let Some(engine) = kasumi_core::core::locked_core_for(proto) {
            locked_by_proto.insert(wire(proto), serde_json::Value::String(wire(engine)));
        }
    }
    let locked_by_proto_json =
        serde_json::to_string_pretty(&serde_json::Value::Object(locked_by_proto))
            .expect("pretty locked core map");
    out.push_str(
        "\n/** The single core a locked protocol can run on, single-sourced from Rust `locked_core_for`. */\n",
    );
    out.push_str("export const LOCKED_CORE_BY_PROTOCOL = ");
    out.push_str(&locked_by_proto_json);
    out.push_str(" as Partial<Record<Protocol, CoreEngine>>;\n");

    let block_templates = kasumi_core::route::builtin_block_templates();
    let block_templates_json =
        serde_json::to_string_pretty(&block_templates).expect("pretty block templates");
    out.push_str("/** Ready-made rule blocks offered when adding a block to a route, single-sourced from Rust core. */\n");
    out.push_str(&format!(
        "export const BLOCK_TEMPLATES = {block_templates_json} as const;\n\n"
    ));

    out
}

/// An enum value's serde wire string (single-sourced from its `Serialize`).
fn wire<T: serde::Serialize>(v: T) -> String {
    serde_json::to_value(v)
        .ok()
        .and_then(|x| x.as_str().map(str::to_owned))
        .unwrap_or_default()
}
